pub const CONSUMER_USAGE_MAX: u16 = kumi_icd::KeyAction::MAX_CONSUMER_USAGE;

pub fn boot_keyboard_report(report: &KeyboardReport) -> [u8; BOOT_KEYBOARD_REPORT_LEN] {
    let mut out = [0u8; BOOT_KEYBOARD_REPORT_LEN];
    out[0] = report.modifiers;
    out[2..2 + ROLLOVER].copy_from_slice(&report.keys);
    out
}

pub fn keyboard_report(report: &KeyboardReport) -> [u8; KEYBOARD_REPORT_LEN] {
    let mut out = [0u8; KEYBOARD_REPORT_LEN];
    out[0] = REPORT_ID_KEYBOARD;
    out[1] = report.modifiers;
    out[3..3 + ROLLOVER].copy_from_slice(&report.keys);
    out
}

pub fn consumer_report(usage: u16) -> [u8; CONSUMER_REPORT_LEN] {
    let usage = if usage > CONSUMER_USAGE_MAX { 0 } else { usage };
    let bytes = usage.to_le_bytes();
    [REPORT_ID_CONSUMER, bytes[0], bytes[1]]
}

pub fn mouse_report(report: &MouseReport) -> [u8; MOUSE_REPORT_LEN] {
    [
        REPORT_ID_MOUSE,
        report.buttons & 0x07,
        report.dx.clamp(-127, 127) as u8,
        report.dy.clamp(-127, 127) as u8,
        report.wheel.clamp(-127, 127) as u8,
    ]
}
